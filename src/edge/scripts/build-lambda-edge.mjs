// Build the Lambda@Edge bundle: bake a per-deployment config into the worker
// at build time (Lambda@Edge has no environment variables), bundle it, and
// smoke-invoke the result so a broken bake fails the build, not the deploy.
//
// The bake mechanism: a generated config module plus a generated wrapper
// entry that copies the config into process.env before re-exporting the real
// handler. The aws-lambda entry reads process.env lazily on the first
// invocation, so the import hoisting of the re-export is harmless. An esbuild
// define is NOT usable here — the entry passes the whole process.env object
// to its parser, and a whole-object define would rewrite every process.env
// read in the bundle, dependencies included.
//
// Usage: node scripts/build-lambda-edge.mjs --config <deploy-config.json>
//        [--out-dir dist/lambda-edge]
//
// The config file is a flat JSON object of env-shaped string values
// (EXCHANGE_URL, EXCHANGE_WBA_URL, PROVIDER, EXCHANGES_JSON, and the optional
// keys the worker's EnvSchema documents). Values must be strings — they stand
// in for environment variables. Output: <out-dir>/index.mjs, plus the two
// generated intermediates next to it.

import { spawnSync } from 'node:child_process';
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    config: { type: 'string' },
    'out-dir': { type: 'string', default: 'dist/lambda-edge' },
  },
});

if (!values.config) {
  console.error('usage: node scripts/build-lambda-edge.mjs --config <deploy-config.json>');
  process.exit(2);
}

const edgeDir = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = resolve(edgeDir, values['out-dir']);

function loadConfig(path) {
  const parsed = JSON.parse(readFileSync(path, 'utf8'));
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new Error(`${path}: config must be a flat JSON object of string values`);
  }
  const nonString = Object.entries(parsed).filter(([, v]) => typeof v !== 'string');
  if (nonString.length > 0) {
    const keys = nonString.map(([k]) => k).join(', ');
    throw new Error(
      `${path}: every value must be a string (they stand in for environment variables); not strings: ${keys}`,
    );
  }
  return parsed;
}

function generateSources(config) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    join(outDir, 'edge-config.mjs'),
    `// Generated by build-lambda-edge.mjs — per-deployment config baked at\n// build time (Lambda@Edge has no environment variables). Do not edit.\nexport const config = ${JSON.stringify(config, null, 2)};\n`,
  );
  // A relative specifier, because esbuild resolves those from the importing
  // file; posix separators so the generated source is a valid ES module path.
  const entryImport = relative(outDir, join(edgeDir, 'src/entries/aws-lambda.ts'))
    .split(sep)
    .join('/');
  writeFileSync(
    join(outDir, 'entry.mjs'),
    `// Generated by build-lambda-edge.mjs. The assign runs before the first\n// invocation reads process.env (the entry reads it lazily), so the baked\n// config is what the env parser sees. Do not edit.\nimport { config } from './edge-config.mjs';\nObject.assign(process.env, config);\nexport { handler } from '${entryImport}';\n`,
  );
}

function bundle() {
  const result = spawnSync(
    process.execPath,
    [
      join(edgeDir, 'scripts/build-worker.mjs'),
      '--entry',
      join(outDir, 'entry.mjs'),
      '--out',
      join(outDir, 'index.mjs'),
      '--platform',
      'node',
    ],
    { cwd: edgeDir, stdio: 'inherit' },
  );
  if (result.status !== 0) {
    throw new Error('bundling failed');
  }
}

function viewerRequestEvent(host, uri, headers = {}) {
  const cfHeaders = { host: [{ key: 'Host', value: host }] };
  for (const [k, v] of Object.entries(headers)) {
    cfHeaders[k.toLowerCase()] = [{ key: k, value: v }];
  }
  return {
    Records: [
      {
        cf: {
          config: {
            distributionDomainName: 'smoke.cloudfront.example',
            distributionId: 'SMOKE',
            eventType: 'viewer-request',
            requestId: 'smoke-1',
          },
          request: {
            clientIp: '127.0.0.1',
            method: 'GET',
            uri,
            querystring: '',
            headers: cfHeaders,
          },
        },
      },
    ],
  };
}

// Invoke the BUILT bundle the way Lambda will: prove the baked config reaches
// the env parser (a bad bake throws here) and both response shapes work — a
// generated response for the manifest route, a pass-through request for an
// authorized read. Importing the bundle assigns the baked config onto this
// process's env; that is confined to this short-lived build process.
async function smokeInvoke(config) {
  const { handler } = await import(pathToFileURL(join(outDir, 'index.mjs')).href);
  const host = config.PROVIDER;

  const manifest = await handler(viewerRequestEvent(host, '/.well-known/ramp.json'));
  if (manifest.status !== '200') {
    throw new Error(`smoke: ramp.json answered status ${manifest.status}, want 200`);
  }
  const domain = JSON.parse(manifest.body ?? '').domain;
  if (domain !== config.PROVIDER) {
    throw new Error(`smoke: ramp.json domain is ${domain}, want ${config.PROVIDER}`);
  }

  const passThrough = await handler(
    viewerRequestEvent(host, '/smoke-article', {
      'user-agent': 'Mozilla/5.0 (Macintosh) Safari/605.1.15',
    }),
  );
  if (!('uri' in passThrough)) {
    throw new Error(
      'smoke: an unsigned human read must pass through as a request object so CloudFront fetches the origin',
    );
  }
}

const config = loadConfig(values.config);
generateSources(config);
bundle();
try {
  await smokeInvoke(config);
} catch (err) {
  // A bundle that failed its smoke invoke must not survive on disk: the zip
  // step never runs on failure, but anything pointing at the directory would
  // otherwise pick up the broken bake.
  rmSync(join(outDir, 'index.mjs'), { force: true });
  throw err;
}
console.log(`built and smoke-invoked ${join(outDir, 'index.mjs')}`);
